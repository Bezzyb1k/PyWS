"""
Тернарный оператор - if в одну строку
"""

# Базовый синтаксис
print("=== Базовый синтаксис ===")
age = 20
status = "Взрослый" if age >= 18 else "Ребенок"
print(f"Статус: {status}")

# Вложенные тернарные операторы
print("\n=== Вложенные тернарные ===")
x = 5
result = "Число положительное" if x > 10 else ("Ноль" if x == 0 else "Число отрицательное")
print(f"x = {x}, результат: {result}")
